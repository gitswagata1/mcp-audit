import type { AuditResult, Finding, Severity, Category } from "./types.js";
import { formatFix } from "./fixes.js";

/** Wrap text in an inline code span that survives backticks inside it. */
function inlineCode(text: string): string {
  const longestRun = Math.max(0, ...(text.match(/`+/g) ?? []).map((r) => r.length));
  const fence = "`".repeat(longestRun + 1);
  const pad = longestRun > 0 ? " " : "";
  return `${fence}${pad}${text}${pad}${fence}`;
}

const SEVERITY_EMOJI: Record<Severity, string> = {
  critical: "\u{1F6D1}",
  high: "\u{1F7E0}",
  medium: "\u{1F7E1}",
  low: "\u{1F535}",
  info: "\u{2139}\u{FE0F}",
};

const CATEGORY_LABELS: Record<Category, string> = {
  "permissions": "Permissions",
  "secrets": "Secrets",
  "supply-chain": "Supply Chain",
  "transport": "Transport",
  "config-hygiene": "Config Hygiene",
  "environment": "Environment",
};

const GRADE_EMOJI: Record<string, string> = {
  A: "\u{1F7E2}",
  B: "\u{1F535}",
  C: "\u{1F7E1}",
  D: "\u{1F7E0}",
  F: "\u{1F534}",
};

export function printMarkdown(result: AuditResult): void {
  const lines: string[] = [];

  lines.push(`## ${GRADE_EMOJI[result.grade]} MCP Security Audit — Grade: ${result.grade} (${result.score}/100)`);
  lines.push("");
  lines.push(`> ${result.servers.length} servers · ${result.findings.length} findings · ${result.scannedPaths.length} configs scanned`);
  lines.push(`> ${result.timestamp}`);
  lines.push("");

  if (result.servers.length > 0) {
    lines.push("### Servers");
    lines.push("");
    lines.push("| Server | Source | Transport | Grade | Findings |");
    lines.push("|--------|--------|-----------|-------|----------|");

    for (const ss of result.serverScores) {
      const server = result.servers.find(s => s.name === ss.server && s.source === ss.source);
      const transport = server?.url ? "Remote" : "stdio";
      const gradeEmoji = GRADE_EMOJI[ss.grade] ?? "";
      lines.push(`| \`${ss.server}\` | ${ss.source} | ${transport} | ${gradeEmoji} ${ss.grade} | ${ss.findingCount} |`);
    }
    lines.push("");
  }

  if (result.findings.length > 0) {
    lines.push("### Findings");
    lines.push("");

    const grouped = new Map<Severity, Finding[]>();
    for (const f of result.findings) {
      const arr = grouped.get(f.severity) ?? [];
      arr.push(f);
      grouped.set(f.severity, arr);
    }

    for (const sev of ["critical", "high", "medium", "low", "info"] as Severity[]) {
      const group = grouped.get(sev);
      if (!group || group.length === 0) continue;

      lines.push(`#### ${SEVERITY_EMOJI[sev]} ${sev.toUpperCase()} (${group.length})`);
      lines.push("");

      for (const f of group) {
        const cat = CATEGORY_LABELS[f.category] ?? f.category;
        lines.push(`- **[${cat}] ${f.title}** — \`${f.server}\``);
        lines.push(`  ${f.detail}`);
        if (sev === "critical" || sev === "high") {
          lines.push(`  > **Fix:** ${f.recommendation}`);
        }
        if (f.fix) {
          lines.push(`  > **Auto-fix:** ${inlineCode(formatFix(f.fix))}`);
        }
      }
      lines.push("");
    }
  } else {
    lines.push("### ✅ No security issues found");
    lines.push("");
  }

  lines.push("---");
  lines.push(`*Generated by [mcp-audit](https://github.com/gitswagata1/mcp-audit) v${result.version}*`);

  console.log(lines.join("\n"));
}
